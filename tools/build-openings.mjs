// Builds src/data/openings.js from the lichess-org/chess-openings TSV files
// (CC0-1.0) stored in tools/openings-src/{a..e}.tsv.
// Run: node tools/build-openings.mjs
// Every line is replayed with engine.js; illegal or unparsable lines abort the
// build. Exact duplicates (same ECO, name and moves) are removed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Position, START_FEN } from '../src/engine.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'tools', 'openings-src');
const OUT = path.join(ROOT, 'src', 'data', 'openings.js');

const rows = [];
const errors = [];
let read = 0;
for (const letter of ['a', 'b', 'c', 'd', 'e']) {
  const text = fs.readFileSync(path.join(SRC, `${letter}.tsv`), 'utf8');
  const lines = text.split(/\r?\n/).filter((l) => l.trim());
  const header = lines.shift().split('\t');
  const iE = header.indexOf('eco'), iN = header.indexOf('name'), iP = header.indexOf('pgn');
  if (iE < 0 || iN < 0 || iP < 0) throw new Error(`${letter}.tsv has an unexpected header: ${header.join(',')}`);
  for (const [n, line] of lines.entries()) {
    read++;
    const cols = line.split('\t');
    const eco = cols[iE].trim(), name = cols[iN].trim(), pgn = cols[iP].trim();
    if (!/^[A-E]\d\d$/.test(eco)) { errors.push(`${letter}.tsv:${n + 2} bad ECO ${eco}`); continue; }
    if (!name || name.includes('|') || name.includes('\n')) { errors.push(`${letter}.tsv:${n + 2} bad name`); continue; }
    const tokens = pgn.split(/\s+/).filter((t) => t && !/^\d+\.+$/.test(t));
    let pos = Position.fromFen(START_FEN);
    const sans = [];
    let ok = true;
    for (const t of tokens) {
      const m = pos.parseSan(t);
      if (!m) { errors.push(`${letter}.tsv:${n + 2} ${eco} ${name}: illegal or unparsable move "${t}" in "${pgn}"`); ok = false; break; }
      sans.push(pos.toSan(m));
      pos = pos.makeMove(m);
    }
    if (!ok) continue;
    if (!sans.length) { errors.push(`${letter}.tsv:${n + 2} empty line`); continue; }
    rows.push({ eco, name, sans: sans.join(' '), hash: pos.hash() });
  }
}
if (errors.length) { console.error(errors.join('\n')); console.error(`${errors.length} lines failed verification. The data file was not written.`); process.exit(1); }

const seen = new Set();
const out = [];
let dupes = 0;
for (const r of rows) {
  const key = `${r.eco}|${r.name}|${r.sans}`;
  if (seen.has(key)) { dupes++; continue; }
  seen.add(key); out.push(r);
}
const byEco = {};
for (const r of out) byEco[r.eco[0]] = (byEco[r.eco[0]] || 0) + 1;
const codes = new Set(out.map((r) => r.eco));
const names = new Set(out.map((r) => r.name));
const positions = new Set(out.map((r) => r.hash));
const sharedPos = out.length - positions.size;

const body = out.map((r) => `${r.eco}|${r.name}|${r.sans}`).join('\n');
const file = `// GENERATED by tools/build-openings.mjs. Do not edit by hand.
// Source: https://github.com/lichess-org/chess-openings (files a.tsv to e.tsv), CC0-1.0.
// Format: one line per opening, "ECO|Name|SAN moves separated by spaces".
// Every line was replayed and verified as legal with src/engine.js.
export const OPENINGS_SOURCE = ${JSON.stringify({ url: 'https://github.com/lichess-org/chess-openings', license: 'CC0-1.0' })};
export const OPENINGS_COUNT = ${out.length};
export const OPENINGS_DATA = ${JSON.stringify(body)};
`;
fs.writeFileSync(OUT, file);
console.log(`Read ${read} lines from 5 files.`);
console.log(`Verified as legal: ${rows.length}. Exact duplicates removed: ${dupes}. Written: ${out.length}.`);
console.log(`Per ECO volume: ${Object.entries(byEco).map(([k, v]) => `${k}=${v}`).join(', ')}.`);
console.log(`Distinct ECO codes: ${codes.size}. Distinct names: ${names.size}. Distinct final positions: ${positions.size} (${sharedPos} lines share a final position with another line).`);
console.log(`Output: ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes).`);
