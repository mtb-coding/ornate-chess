// Builds src/data/opening-library.js from tools/opening-library-spec.mjs.
// Every name and move sequence is checked against the lichess dataset and the
// rules engine. Usage: node tools/build-opening-library.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Position, START_FEN } from '../src/engine.js';
import { SPEC, CATEGORIES } from './opening-library-spec.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rows = [];
for (const f of ['a', 'b', 'c', 'd', 'e']) {
  for (const line of fs.readFileSync(path.join(ROOT, 'tools/openings-src', `${f}.tsv`), 'utf8').split('\n').slice(1)) {
    if (!line.trim()) continue;
    const [eco, name, pgn] = line.split('\t');
    rows.push({ eco, name, pgn });
  }
}
const errors = [];
const out = [];
const ids = new Set();
for (const [category, side, name, pgn, desc] of SPEC) {
  const row = rows.find((r) => r.name === name && r.pgn === pgn);
  if (!row) { errors.push(`Not in the dataset: ${name} | ${pgn}`); continue; }
  const sans = pgn.replace(/\d+\.\s*/g, '').trim().split(/\s+/);
  let pos = Position.fromFen(START_FEN);
  for (const s of sans) { const m = pos.parseSan(s); if (!m) { errors.push(`Illegal ${s} in ${name}`); break; } pos = pos.makeMove(m); }
  let id = name.toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  if (ids.has(id)) id += `-${sans.length}`;
  ids.add(id);
  out.push({ id, eco: row.eco, name, moves: sans.join(' '), category, side, description: desc });
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
const header = `// Generated by tools/build-opening-library.mjs from tools/opening-library-spec.mjs.\n// Names, ECO codes and moves come from lichess-org/chess-openings (CC0-1.0).\n`;
fs.writeFileSync(path.join(ROOT, 'src/data/opening-library.js'), `${header}export const LIBRARY_CATEGORIES = ${JSON.stringify(CATEGORIES, null, 1)};\n\nexport const LIBRARY = ${JSON.stringify(out, null, 1)};\n`);
console.log(`Wrote ${out.length} openings.`);
